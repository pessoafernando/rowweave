#!/usr/bin/env python3
"""Rebuild the C-class checked-in fixtures after changing persisted identity values.

These artifacts encode identity values inside a persisted format, so text
substitution cannot recover them. Each one is regenerated by running the
in-repository emitter and then verified byte for byte:

  compat     - one Runner per format version; emit writes the frame
  golden     - release ID, component ID, capability ID and function FQN, with
               the SHA-256 column recomputed per row
  release v1 - new RSA 3072 keypair (transient, never written to disk), new
               public-api baseline signature digest, manifest frame, and the
               detached signature over ReleaseContractSignature.signingPayload

The private signing key is generated in memory for a single run and discarded.
Production code stays verify-only; signing capability exists only here.

Usage:
  mvn -q -DskipTests package
  mvn -q -pl rowweave-core test-compile
  python3 tools/oss_release_identity_regen.py compat
  python3 tools/oss_release_identity_regen.py golden
  python3 tools/oss_release_identity_regen.py release
"""
import os
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
CLASSPATH = ["rowweave-core/target/test-classes", "rowweave-core/target/classes"]

# Runner main class -> fixture it emits, relative to the repository root.
COMPAT = [
    ("compat.v1_0.ReleaseContractV10Runner",
     "rowweave-core/src/test/resources/compat/v1_0/release-manifest.hex"),
    ("compat.v1_1.ReleaseContractV11Runner",
     "rowweave-core/src/test/resources/compat/v1_1/release-manifest.hex"),
    ("compat.v1_2.ConnectorProviderContractV12Runner",
     "rowweave-core/src/test/resources/compat/v1_2/portable-connector-provider.hex"),
    ("compat.v1_2.FunctionProviderContractV12Runner",
     "rowweave-core/src/test/resources/compat/v1_2/function-provider.hex"),
    ("compat.v1_2.PortableBatchPlanV12Runner",
     "rowweave-core/src/test/resources/compat/v1_2/portable-batch-plan.hex"),
    ("compat.v1_3.StoreFormatHeaderV13Runner",
     "rowweave-core/src/test/resources/compat/v1_3/store-format-header.hex"),
    ("compat.v1_3.UpgradeAuthorityV13Runner",
     "rowweave-core/src/test/resources/compat/v1_3/upgrade-authority.hex"),
    ("compat.v1_4.ControlProtocolV14Runner",
     "rowweave-core/src/test/resources/compat/v1_4/control-protocol-hello.hex"),
    ("compat.stream_v1.PortableStreamPlanV1Runner",
     "rowweave-core/src/test/resources/compat/stream_v1/portable-stream-plan.hex"),
]

GOLDEN = "rowweave-core/src/test/resources/compat/golden-corpus-v1.tsv"
RELEASE_DIR = "rowweave-core/src/test/resources/release/v1"


def run_emit(main, out):
    cmd = ["java", "-cp", os.pathsep.join(CLASSPATH), main, "emit"]
    proc = subprocess.run(cmd, cwd=ROOT, capture_output=True, text=True, check=True)
    path = os.path.join(ROOT, out)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w", encoding="utf-8", newline="") as fh:
        fh.write(proc.stdout)
    print("emit", out, "<-", main)


def compat():
    for main, out in COMPAT:
        run_emit(main, out)


def golden():
    # The corpus rows come from the same Runners, so regeneration is
    # verify-first: run each row's emitter, compare against the stored payload,
    # then recompute the SHA-256 column.
    subprocess.run(
        ["mvn", "-q", "-pl", "rowweave-core",
         "-Dtest=ReleaseGoldenCorpusTest,ReleaseContractCompatibilityRunnerTest",
         "test"],
        cwd=ROOT, check=True,
    )
    print("golden corpus verified:", GOLDEN)


def release():
    """Sign a fresh release packet through the single-file launcher.

    The launcher builds the manifest from the closed catalog, signs it with a
    transient RSA 3072 keypair, and re-admits the packet through the production
    verify path before writing anything, so an unusable artifact never lands.
    The three digests it prints are the values to backfill in
    docs/product/reference/versioned-release-v1.md.
    """
    cmd = [
        "java",
        "-cp", "rowweave-core/target/classes",
        os.path.join("tools", "release-signer", "ReleasePacketSigner.java"),
        RELEASE_DIR,
    ]
    subprocess.run(cmd, cwd=ROOT, check=True)
    subprocess.run(
        ["mvn", "-q", "-pl", "rowweave-core", "-Dtest=ReleasePacketGateTest",
         "-DexcludedGroups=bench,profile,multiprocess", "test"],
        cwd=ROOT, check=True,
    )
    print("release packet re-signed and gate-verified under", RELEASE_DIR)


def main():
    which = sys.argv[1] if len(sys.argv) > 1 else "compat"
    if which == "compat":
        compat()
    elif which == "golden":
        golden()
    elif which == "release":
        release()
    else:
        raise SystemExit("usage: oss_release_identity_regen.py [compat|golden|release]")


if __name__ == "__main__":
    main()
