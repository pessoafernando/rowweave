package io.rowweave.cluster;

import io.rowweave.DataType;
import io.rowweave.DiscardSink;
import io.rowweave.Field;
import io.rowweave.DataSchema;
import io.rowweave.cluster.rpc.RpcMessage;
import io.rowweave.plan.PlanGraph;
import io.rowweave.plan.PlanNode;
import io.rowweave.run.RunAttemptFence;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

import java.io.File;
import java.nio.file.Path;
import java.util.Arrays;
import java.util.Collections;

import static org.junit.jupiter.api.Assertions.*;

class WorkerIncarnationFenceTest {

    private static final RunAttemptFence FENCE =
            new RunAttemptFence("worker-run", "worker-attempt", 1L);

    @Test
    void wrongIncarnationAssignAndCancelHaveNoLedgerSideEffects(@TempDir Path tmp) {
        DataSchema meta = new DataSchema(new Field("v", DataType.IntegerType));
        PlanGraph graph = new PlanGraph(Arrays.asList(
                PlanNode.source(meta, Collections.emptyList()),
                PlanNode.sink(meta, 0, new DiscardSink(meta)).build()));
        try (MasterServer master = new MasterServer(60_000L);
             WorkerServer worker = WorkerServer.newUnguarded(
                     "w", 2, "127.0.0.1", master.port(), new File(tmp.toFile(), "worker"))) {
            assertEquals(worker.incarnationId(), master.worker("w").incarnationId(),
                    "the token generated by the Worker reaches Master WorkerInfo through REGISTER");
            RpcMessage rejected = worker.handler().apply(RpcMessage.assignStageInProcess(
                    "w", 70_001L, StageCommand.wholeGraph(graph), "wrong-incarnation"));
            assertEquals(RpcMessage.Type.JOB_RESULT, rejected.type());
            assertFalse(rejected.success());
            assertTrue(rejected.errorMessage().contains("incarnation"), rejected.errorMessage());
            assertEquals(2L, worker.freeSlots(), "a wrong ASSIGN takes no slot");

            assertEquals(RpcMessage.Type.ACK, worker.handler().apply(
                    RpcMessage.cancelStage("w", 70_002L, "wrong-incarnation")).type());
            assertEquals(RpcMessage.Type.ACK, worker.handler().apply(
                    RpcMessage.rollbackPreparedOutput(
                            "w", 70_003L, "group", "wrong-incarnation")).type());
            assertEquals(0, worker.preparedOutputEntryCount(),
                    "Sink control from an older generation creates no tombstone and does not touch replacement state");
            assertEquals(RpcMessage.Type.ACK, worker.handler().apply(
                    RpcMessage.rollbackPreparedOutput(
                            "w", 70_003L, "group", worker.incarnationId(), FENCE)).type());
            assertEquals(1, worker.preparedOutputEntryCount());
            RpcMessage accepted = worker.handler().apply(RunAttemptFenceTestSupport.inProcess(
                    "w", 70_002L, StageCommand.wholeGraph(graph), worker.incarnationId()));
            assertEquals(RpcMessage.Type.ACK, accepted.type(),
                    "a wrong CANCEL creates no negative tombstone that would reject the correct ASSIGN");
        }
    }

    @Test
    void currentGenerationCancelRollsBackPreparedOutput(@TempDir Path tmp) throws Exception {
        try (MasterServer master = new MasterServer(60_000L);
             WorkerServer worker = WorkerServer.newUnguarded(
                     "cancel-output-worker", 1, "127.0.0.1", master.port(), tmp.toFile())) {
            TrackingOutput output = new TrackingOutput();
            preparedOutputs(worker).register("cancel-group", 80_001L, output, FENCE);

            RpcMessage response = worker.handler().apply(RpcMessage.cancelStage(
                    "cancel-output-worker", 80_001L, worker.incarnationId(), FENCE));

            assertEquals(RpcMessage.Type.ACK, response.type());
            assertEquals(1, output.rollbackCalls);
            assertEquals(0, worker.preparedOutputActiveCount());
        }
    }

    @Test
    void cancellationBeforeLatePreparedRegistrationUsesKnownCommitGroupTombstone(
            @TempDir Path tmp) throws Exception {
        DataSchema meta = new DataSchema(new Field("v", DataType.IntegerType));
        PlanGraph graph = new PlanGraph(Arrays.asList(
                PlanNode.source(meta, Collections.emptyList()),
                PlanNode.sink(meta, 0, new DiscardSink(meta)).build()));
        try (MasterServer master = new MasterServer(60_000L);
             WorkerServer worker = WorkerServer.newUnguarded(
                     "late-output-worker", 1, "127.0.0.1", master.port(), tmp.toFile())) {
            long stageId = 80_003L;
            StageCommand command = StageCommand.wholeGraph(graph)
                    .withCommitGroupId("late-output-group")
                    .withRunAttemptFence(FENCE);
            WorkerAssignmentLedger ledger = assignments(worker);
            WorkerAssignmentLedger.Registration registration =
                    ledger.registerInProcess(stageId, command, FENCE);
            assertEquals(WorkerAssignmentLedger.Decision.NEW, registration.decision);
            assertFalse(ledger.attachCommand(registration.slot, command));

            RpcMessage cancelled = worker.handler().apply(RpcMessage.cancelStage(
                    "late-output-worker", stageId, worker.incarnationId(), FENCE));
            assertEquals(RpcMessage.Type.ACK, cancelled.type());

            TrackingOutput late = new TrackingOutput();
            assertFalse(preparedOutputs(worker).register(
                    "late-output-group", stageId, late, FENCE),
                    "late EOS handoff must observe the cancellation tombstone");
            assertEquals(1, late.rollbackCalls);
            assertEquals(0, worker.preparedOutputActiveCount());
        }
    }

    @Test
    void currentGenerationRequiresExactAttemptFenceBeforeMutation(@TempDir Path tmp)
            throws Exception {
        try (MasterServer master = new MasterServer(60_000L);
             WorkerServer worker = WorkerServer.newUnguarded(
                     "attempt-control-worker", 1, "127.0.0.1", master.port(), tmp.toFile())) {
            long stageId = 80_002L;
            RunAttemptFence stale = new RunAttemptFence("worker-run", "stale-attempt", 2L);
            TrackingOutput output = new TrackingOutput();
            preparedOutputs(worker).register("attempt-group", stageId, output, FENCE);
            assignments(worker).registerInProcess(stageId, new Object(), FENCE);

            RpcMessage staleCancel = worker.handler().apply(RpcMessage.cancelStage(
                    "attempt-control-worker", stageId, worker.incarnationId(), stale));
            assertEquals(RpcMessage.Type.JOB_RESULT, staleCancel.type());
            assertFalse(staleCancel.success());
            assertTrue(staleCancel.errorMessage().contains("fence"), staleCancel.errorMessage());
            assertEquals(0, output.rollbackCalls);
            assertEquals(0L, worker.freeSlots());

            RpcMessage missingCommit = worker.handler().apply(RpcMessage.commitPreparedOutput(
                    "attempt-control-worker", stageId, "attempt-group", worker.incarnationId()));
            RpcMessage staleRollback = worker.handler().apply(RpcMessage.rollbackPreparedOutput(
                    "attempt-control-worker", stageId, "attempt-group",
                    worker.incarnationId(), stale));
            assertFalse(missingCommit.success());
            assertFalse(staleRollback.success());
            assertTrue(missingCommit.errorMessage().contains("fence"), missingCommit.errorMessage());
            assertTrue(staleRollback.errorMessage().contains("fence"), staleRollback.errorMessage());
            assertEquals(0, output.commitCalls);
            assertEquals(0, output.rollbackCalls);

            RpcMessage committed = worker.handler().apply(RpcMessage.commitPreparedOutput(
                    "attempt-control-worker", stageId, "attempt-group",
                    worker.incarnationId(), FENCE));
            assertEquals(RpcMessage.Type.ACK, committed.type());
            assertEquals(1, output.commitCalls);

            RpcMessage cancelled = worker.handler().apply(RpcMessage.cancelStage(
                    "attempt-control-worker", stageId, worker.incarnationId(), FENCE));
            assertEquals(RpcMessage.Type.ACK, cancelled.type());
            assertEquals(1, output.rollbackCalls);
        }
    }

    private static PreparedOutputRegistry preparedOutputs(WorkerServer worker) throws Exception {
        java.lang.reflect.Field field = WorkerServer.class.getDeclaredField("preparedOutputs");
        field.setAccessible(true);
        return (PreparedOutputRegistry) field.get(worker);
    }

    private static WorkerAssignmentLedger assignments(WorkerServer worker) throws Exception {
        java.lang.reflect.Field field = WorkerServer.class.getDeclaredField("assignments");
        field.setAccessible(true);
        return (WorkerAssignmentLedger) field.get(worker);
    }

    private static final class TrackingOutput implements io.rowweave.Sink {
        private static final long serialVersionUID = 1L;
        int rollbackCalls;
        int commitCalls;

        @Override public DataSchema getSchema() {
            return new DataSchema(new Field("v", DataType.IntegerType));
        }
        @Override public void collect(io.rowweave.DataRow row) { }
        @Override public boolean supportsCoordinatedCommit() { return true; }
        @Override public void prepareCommit() { }
        @Override public void commitPrepared() { commitCalls++; }
        @Override public void rollbackCommit() { rollbackCalls++; }
        @Override public void finalizeCommit() { }
    }
}

